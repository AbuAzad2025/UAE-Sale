def normalize(text: str) -> str:
    """تطبيع: أرقام + أليف + تاء مربوطة + ة/ه + ى + إزالة تشكيل/تطويل."""
    if not text:
        return ''
    s = str(text)
    # أليف/تاء/تشكيل أولاً حتى يطابق "ألف/مائة/ثلاثة" مع مفاتيحنا غير الموسومة
    s = _AR_DIACRITICS.sub('', s)
    s = s.replace('إ', 'ا').replace('أ', 'ا').replace('آ', 'ا')
    s = s.replace('ة', 'ه').replace('ۀ', 'ه')
    s = s.replace('ى', 'ي').replace('ئ', 'ي').replace('ؤ', 'و').replace('ء', '')
    # أرقام حروفاً: ألف/مئة/خمسين... → رقمية
    for _ar_w, _lat in _AR_WORD_NUMBERS.items():
        s = s.replace(_ar_w, _lat)
    for ar, lat in _AR_NUMBERS.items():
        s = s.replace(ar, lat)
    s = _PUNCT.sub(' ', s)
    s = s.lower()
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def tokenize(text: str, expand_synonyms: bool = True) -> list[str]:
    """تقسيم + إزالة قصير + توسيع مرادفات (مع الاحتفاظ بالأصل)."""
    norm = normalize(text)
    if not norm:
        return []
    words = [w for w in norm.split() if len(w) > 1]
    if expand_synonyms:
        extra: list[str] = []
        for w in words:
            for syn in _SYNONYMS.get(w, []):
                extra.append(normalize(syn))
        words = words + [w for w in extra if len(w) > 1]
    return words


def expand_synonyms(text: str) -> str:
    """نص مُطبَّع مع مرادفاته (للأغراض البحثية)."""
    return ' '.join(tokenize(text))


def cosine_sim(a: dict[str, float], b: dict[str, float]) -> float:
    """جيب تمام لمتجهين متناثرين."""
    if not a or not b:
        return 0.0
    # المحصلة
    dot = sum(v * b[k] for k, v in a.items() if k in b)
    norm_a = sum(v * v for v in a.values()) ** 0.5
    norm_b = sum(v * v for v in b.values()) ** 0.5
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return dot / (norm_a * norm_b)
